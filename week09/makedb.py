def main():
    # DB 경로는 스크립트 위치 기준
    db_path = os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "security_concepts.db"
    )

    con = sqlite3.connect(db_path)
    cur = con.cursor()

    # 기존 테이블 초기화
    cur.execute("DROP TABLE IF EXISTS security_concepts")

    # 테이블 생성
    cur.execute(
        """CREATE TABLE security_concepts (
        id INTEGER PRIMARY KEY,
        name TEXT,
        category TEXT,
        description TEXT,
        example TEXT,
        keywords TEXT,
        source_url TEXT,
        embedding BLOB
    )"""
    )

    # 데이터 삽입 (SQL 파라미터 사용)
    cur.executemany(
        """
        INSERT INTO security_concepts (name, category, description, example, keywords, source_url)
        VALUES (?, ?, ?, ?, ?, ?)
    """,
        ROWS,
    )

    con.commit()

    # 삽입한 행 수 출력
    count = cur.execute("SELECT COUNT(*) FROM security_concepts").fetchone()[0]
    print(f"{count} 행 생성 완료.")

    con.close()


if __name__ == "__main__":
    main()
